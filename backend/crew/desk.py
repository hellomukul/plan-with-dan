"""Dan's Desk: the chief-of-staff loop.

1. scan()   (code)  reads the student's plan, requirements, deadlines, bids,
                    profile and Global Studies budget, and emits typed decision
                    cards. Every card has a due date from the SOM calendar or a
                    rule, an action, and a `source` naming the tool or rule behind it.
2. brief()  (agent) the Chief of Staff agent writes 2-3 sentences from the top
                    cards only. It is cached per student per day per set of cards,
                    so the home page costs about one small model call a day.
3. Student  approves (opens the action), snoozes (3 days) or dismisses a card.

Dates are never generated by the model. They come from rules.CALENDAR or are
computed here.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass, field
from datetime import date, datetime, timedelta, timezone

from sqlmodel import Session, select

from catalog import TERM_NAMES
from config import ai_available
from crew.runtime import Run
from db import DeskBrief, DeskState, aware, utcnow
from planning import PlanRow, conflicts, requirement_progress
from rules import CALENDAR, GSA_DAYS
from safety import BudgetExceeded, SpendGuard, fence

PLANNING_TERM = "202701"
ADD_DROP = {"202603": ("2026-11-02", "Fall session-2 add/drop"), "202701": ("2027-01-26", "Spring add/drop")}
SEVERITY = {"high": 0, "medium": 1, "low": 2}
TOP_N = 3


@dataclass
class Card:
    kind: str
    title: str
    detail: str
    due: str | None  # ISO date
    severity: str
    action: dict
    source: str
    key: str = ""
    why: str = ""
    id: str = field(default="")

    def __post_init__(self) -> None:
        self.id = hashlib.sha1(f"{self.kind}|{self.key}".encode()).hexdigest()[:12]

    def as_dict(self, today: date) -> dict:
        days = (date.fromisoformat(self.due) - today).days if self.due else None
        return {**self.__dict__, "days_left": days}


def scan(profile: dict, plan: list[PlanRow], catalog, global_choices: list[dict], bid_points: dict[str, int | None],
         today: date) -> list[Card]:
    cards: list[Card] = []
    prog = requirement_progress(profile, plan, catalog, global_choices)
    year = profile.get("year") or ""

    # 1. Clashes, due by that term's add/drop.
    for term in sorted({r.section.term for r in plan}):
        for c in conflicts([r.section for r in plan if r.section.term == term]):
            due, label = ADD_DROP.get(term, (None, "add/drop"))
            cards.append(Card(
                kind="clash", key=f"{c['a_id']}-{c['b_id']}", severity="high", due=due,
                title=f"Fix the clash: {c['a']} vs {c['b']}",
                detail=f"{TERM_NAMES.get(term, term)}, {c['day']} {c['window']}. Overlapping courses get dropped after {label}.",
                action={"type": "go", "route": "plan", "label": "Fix clash"},
                source="planning.conflicts (real session dates)",
                why="SOM removes one of two overlapping courses after add/drop.",
            ))

    # 2. Planning term below the 16-unit minimum (first three terms only).
    term_units = sum(r.section.units for r in plan if r.section.term == PLANNING_TERM)
    if year in ("1", "2", "") and term_units < 16:
        short = 16 - term_units
        cards.append(Card(
            kind="units_low", key=PLANNING_TERM, severity="high" if term_units else "medium",
            due=ADD_DROP[PLANNING_TERM][0],
            title=f"Add {short:g} more units to Spring 2027",
            detail=f"You have {term_units:g} of the 16-unit minimum. Your best fits below all fit your timetable.",
            action={"type": "scroll", "target": "fits", "label": "See best fits"},
            source="rules.DEGREE min_units_first_three_terms",
            why="Each of the first three terms needs at least 16 graded units; a heavy term doesn't make up for a light one.",
        ))

    # 3. A real calendar deadline in the next 14 days.
    soon = [(d, label, kind) for d, label, kind in CALENDAR
            if kind == "deadline" and 0 <= (date.fromisoformat(d) - today).days <= 14]
    for d, label, _ in soon[:1]:
        cards.append(Card(
            kind="deadline", key=d, severity="medium", due=d,
            title=label.split(" (")[0],
            detail="Check your courses for that session before the deadline: changes after it need a late form and a $25 fee.",
            action={"type": "go", "route": "calendar", "label": "Open calendar"},
            source="rules.CALENDAR (SOM academic calendar)",
            why="From the SOM academic calendar.",
        ))

    # 4. Global Studies not planned yet.
    gsr = prog["gsr"]
    if not gsr["met"] and not gsr["in_plan"] and not global_choices:
        used = int(profile.get("gsa_days_used", 0) or 0)
        left = GSA_DAYS - used
        ie_note = "an International Experience is still possible (it needs all 10)" if used == 0 else \
            "an International Experience is off the table (it needs all 10 unused)"
        cards.append(Card(
            kind="gsr", key="gsr", severity="medium" if year == "2" else "low", due="2027-03-08",
            title="Pick a Global Studies path",
            detail=f"You have {left} of {GSA_DAYS} funded days, so {ie_note}. Next Global Network Week: Mar 8–12.",
            action={"type": "go", "route": "global", "label": "Compare options"},
            source="rules.GSR_OPTIONS + planning.gsa_check",
            why="The Global Studies Account is never topped up; unused days are forfeited.",
        ))

    # 5. Leadership requirement not covered.
    if not prog["ldr"]["met"]:
        cards.append(Card(
            kind="ldr", key="ldr", severity="low", due=None,
            title="Plan a Leadership (LDR) course",
            detail="You need one approved leadership elective before graduation. Best fits marks courses that count.",
            action={"type": "scroll", "target": "fits", "label": "Show LDR courses"},
            source="rules.LDR (MGLD flag, inferred)",
            why="Required to graduate.",
        ))

    # 6. Bid courses planned but no points set.
    bid_courses = sorted({r.section.number for r in plan if r.section.term == PLANNING_TERM
                          and r.section.enrollment.lower() == "bid" and r.status != "completed"})
    if len(bid_courses) >= 2 and not any(bid_points.get(n) for n in bid_courses):
        cards.append(Card(
            kind="bids", key=",".join(bid_courses), severity="medium", due=None,
            title=f"Set your bid split for {len(bid_courses)} courses",
            detail="Pick must-haves and let the Bid Coach split your points before the spring auction (dates on the internal site).",
            action={"type": "go", "route": "bids", "label": "Split points"},
            source="planning.suggest_bids",
            why="Spreading points evenly is how students lose the course they wanted most.",
        ))

    # 7. Courses with no published time.
    tba = sorted({r.section.number for r in plan if not r.section.meeting and r.status != "completed"})
    if tba:
        cards.append(Card(
            kind="tba", key=",".join(tba), severity="low", due=None,
            title=f"Check meeting times for {', '.join(tba[:3])}",
            detail="SOM hasn't published a time yet, so clash checks can't cover these courses.",
            action={"type": "go", "route": "plan", "label": "Open plan"},
            source="catalog (Daytimes missing)",
        ))

    # 8. No goals, so best fits can't be personal.
    if not (profile.get("goal_short") or profile.get("goal_long")):
        cards.append(Card(
            kind="profile", key="goals", severity="medium", due=None,
            title="Tell Dan your goals",
            detail="Best fits rank courses against your short- and long-term goals.",
            action={"type": "go", "route": "profile", "label": "Add goals"},
            source="profile",
        ))

    def order(c: Card):
        due = date.fromisoformat(c.due) if c.due else date(2100, 1, 1)
        return (SEVERITY[c.severity], due)

    return sorted(cards, key=order)


def apply_states(db: Session, user_id: int, cards: list[Card]) -> tuple[list[Card], list[Card]]:
    """Split into (visible, hidden) using snooze/dismiss/done records."""
    states = {s.card_id: s for s in db.exec(select(DeskState).where(DeskState.user_id == user_id)).all()}
    now = utcnow()
    visible, hidden = [], []
    for c in cards:
        s = states.get(c.id)
        if s and (s.status in ("dismissed", "done") or (s.status == "snoozed" and s.until and aware(s.until) > now)):
            hidden.append(c)
        else:
            visible.append(c)
    return visible, hidden


def set_state(db: Session, user_id: int, card_id: str, status: str) -> None:
    for s in db.exec(select(DeskState).where(DeskState.user_id == user_id, DeskState.card_id == card_id)).all():
        db.delete(s)
    if status != "active":
        until = utcnow() + timedelta(days=3) if status == "snoozed" else None
        db.add(DeskState(user_id=user_id, card_id=card_id, status=status, until=until))
    db.commit()


def _fallback_brief(cards: list[Card], name: str) -> str:
    if not cards:
        return f"You're all caught up{', ' + name if name else ''}: no clashes, deadlines or open decisions right now."
    first = cards[0]
    rest = len(cards) - 1
    return f"{first.title}. " + (f"{rest} more decision{'s' if rest > 1 else ''} below." if rest else "")


async def brief(db: Session, user_id: int, name: str, profile: dict, cards: list[Card], today: date) -> dict:
    """The day's brief, from cache when the cards haven't changed."""
    top = cards[:TOP_N]
    payload = [{"title": c.title, "detail": c.detail, "due": c.due} for c in top]
    digest = hashlib.sha1(json.dumps(payload, sort_keys=True).encode()).hexdigest()[:16]
    day = today.isoformat()
    cached = db.exec(select(DeskBrief).where(DeskBrief.user_id == user_id, DeskBrief.day == day,
                                             DeskBrief.cards_hash == digest)).first()
    if cached:
        return {"text": cached.text, "cached": True, "run_id": cached.run_id, "cost_usd": 0.0}
    if not ai_available() or not top:
        text = _fallback_brief(top, name)
        db.add(DeskBrief(user_id=user_id, day=day, cards_hash=digest, text=text))
        db.commit()
        return {"text": text, "cached": False, "run_id": "", "cost_usd": 0.0}

    from crew.agents import chief  # local import keeps module import light

    run = Run(db=db, user_id=user_id, feature="desk", guard=SpendGuard.for_user(db, user_id))
    prompt = (
        f"Today is {day}. Student first name: {name or 'there'}. "
        f"Year {profile.get('year') or '?'}; short-term goal: {profile.get('goal_short') or 'not set'}.\n"
        f"DECISION CARDS (the only facts you may use):\n{fence(json.dumps(payload, indent=1), 'desk_cards')}"
    )
    try:
        result = await run.call(chief, prompt, name="Chief of Staff", requests=2)
        text = result.output.text.strip()
    except BudgetExceeded:
        text = _fallback_brief(top, name)
    except Exception as exc:  # the desk still works without a brief
        run.audit("agent_error", agent="Chief of Staff", detail=str(exc)[:200])
        text = _fallback_brief(top, name)
    db.add(DeskBrief(user_id=user_id, day=day, cards_hash=digest, text=text, run_id=run.run_id))
    db.commit()
    return {"text": text, "cached": False, "run_id": run.run_id, "cost_usd": run.totals()["cost_usd"]}


def utc_today() -> date:
    return datetime.now(timezone.utc).astimezone().date()
